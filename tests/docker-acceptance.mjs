import assert from "node:assert/strict";
import crypto from "node:crypto";
import { execFileSync } from "node:child_process";
const base = "http://127.0.0.1:8080";
const headers = { authorization: "Bearer dev-local-key", "content-type": "application/json" };
const waitReady = async () => { for (let i=0;i<60;i++) { try { if ((await fetch(`${base}/readyz`)).ok) return; } catch {} await new Promise(r=>setTimeout(r,1000)); } throw new Error("gateway did not become ready"); };
await waitReady();
const runId = Date.now();
const marker = `My code is 7421 (${runId})`;
const sms = JSON.stringify({ smsId: `acceptance-${runId}`, sender: "+13025559876", message: marker, deviceId: "android-sim-01", webhookEvent: "MESSAGE_RECEIVED" });
const signature = crypto.createHmac("sha256", "dev-webhook-secret").update(sms).digest("hex");
for (let i=0;i<2;i++) { const r = await fetch(`${base}/webhooks/textbee/textbee-dev`, { method:"POST", headers:{"content-type":"application/json","x-signature":signature}, body:sms }); assert.equal(r.status,200); }
await new Promise(r=>setTimeout(r,300));
execFileSync("docker", ["compose", "-f", "docker-compose.dev.yml", "restart", "gateway"], { stdio:"inherit" });
await waitReady();
let conversation = await (await fetch(`${base}/v1/conversations?endpointId=android-home-01&counterpart=%2B13025559876`, {headers})).json();
assert.equal(conversation.data.turns.filter(t=>t.content === marker).length, 1);
const callRes = await fetch(`${base}/v1/dev/simulate/calls`, {method:"POST",headers,body:JSON.stringify({endpointId:"android-home-01",from:"3025559876"})});
const call = (await callRes.json()).data;
await new Promise(r=>setTimeout(r,300));
const voice = await fetch(`${base}/v1/calls/${call.id}/voice-session`, {method:"POST",headers,body:JSON.stringify({provider:"stub"})});
assert.equal(voice.status,201); assert.equal((await voice.json()).data.contextIncluded,true);
for (const turn of [{role:"user",text:"What code did I give you?"},{role:"assistant",text:"7421"}]) await fetch(`${base}/v1/dev/simulate/calls/${call.id}/transcript`, {method:"POST",headers,body:JSON.stringify(turn)});
await fetch(`${base}/v1/calls/${call.id}/hangup`, {method:"POST",headers,body:"{}"});
await new Promise(r=>setTimeout(r,300));
execFileSync("docker", ["compose", "-f", "docker-compose.dev.yml", "restart", "gateway"], { stdio:"inherit" });
await waitReady();
conversation = await (await fetch(`${base}/v1/conversations?endpointId=android-home-01&counterpart=%2B13025559876`, {headers})).json();
const text = conversation.data.turns.map(t=>t.content).join(" ");
assert.match(text,new RegExp(marker.replace(/[()]/g,"\\$&"))); assert.match(text,/What code did I give you/);
assert.equal((await fetch(`${base}/v1/messages`,{method:"POST",headers,body:JSON.stringify({from:"android-home-01",to:"+13025559876",body:"Confirmed"})})).status,201);
assert.equal((await fetch(`${base}/v1/calls`,{method:"POST",headers,body:JSON.stringify({from:"android-home-01",to:"+13025559876"})})).status,201);
console.log("PASS: Docker mock acceptance — durable SMS, dedupe, restart, simulated call/media context, transcript, outbound SMS/call");
